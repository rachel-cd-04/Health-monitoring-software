-- Astro Health Monitor · Supabase (PostgreSQL)
-- Access only through the backend (service key). RLS is enabled with no public policies.
create extension if not exists vector;

create table astronauts (
  id serial primary key,
  name text not null,
  role text check (role in ('crew','commander')) default 'crew',
  avatar text,                         -- avatar id/url (fictional)
  pin_hash text,                       -- bcrypt hash of the 4-digit PIN (demo PINs are fictional)
  failed_pin_attempts smallint not null default 0,
  locked_until timestamptz,            -- set after 3 wrong PINs (30 s)
  mission_start date,                  -- mission day = today - mission_start
  baseline jsonb                       -- personal baseline per indicator, e.g. {"heart_rate":{"mean":62,"sd":4}}
);

create table sources (
  id text primary key,                 -- e.g. 'nasa-risks-cardio'
  agency text not null,                -- NASA | CSA
  title text not null,
  url text not null,
  doc_type text,                       -- hazard | risk | research | article
  accessed_on date
);

create table measurements (
  id bigserial primary key,
  astronaut_id int not null references astronauts(id),
  indicator text not null,             -- heart_rate, bp_systolic, bp_diastolic, blood_sugar, temperature, exercise_min
  value numeric not null,
  unit text not null,
  ts timestamptz not null default now(),
  source text not null check (source in ('manual','simulated','sensor')),
  mission_phase text,                  -- pre | in_flight | post (NASA Standard Measures pattern)
  extra jsonb                          -- extra type-specific fields if needed
);

create table checkins (
  id bigserial primary key,
  astronaut_id int not null references astronauts(id),
  day date not null,
  sleep_hours numeric check (sleep_hours between 0 and 24),
  mood smallint check (mood between 1 and 5),
  fatigue smallint check (fatigue between 1 and 5),
  source text not null check (source in ('manual','simulated')),
  unique (astronaut_id, day)
);

-- Synced from backend/src/rules/rules.yaml at startup (YAML is the source of truth)
create table rules (
  id text not null,                    -- S-01
  version int not null default 1,
  indicator text not null,
  body_system text,
  condition text not null,
  level text check (level in ('green','amber','red')),
  who_acts text[] not null default '{self}',  -- self | crew | ground
  description text not null,
  actions text[],
  source_id text references sources(id),
  primary key (id, version)
);

create table alerts (
  id bigserial primary key,
  astronaut_id int not null references astronauts(id),
  rule_id text not null,
  rule_version int not null,
  indicator text not null,
  value numeric,                       -- triggering value (constitution #3)
  measurement_id bigint references measurements(id),
  level text not null,
  message text not null,
  ts timestamptz not null default now(),
  active boolean not null default true,
  acknowledged_at timestamptz,
  foreign key (rule_id, rule_version) references rules(id, version)
);
-- at most one active alert per astronaut + rule
create unique index alerts_one_active on alerts (astronaut_id, rule_id) where active;

-- Emergency mode (HM-05): every step and vital is timestamped
create table emergency_events (
  id uuid primary key default gen_random_uuid(),   -- may be generated by the client
  patient_id int not null references astronauts(id),
  reporter_id int references astronauts(id),
  scenario text not null,              -- chest_pain | collapsed | breathing | bleeding | other
  started_at timestamptz not null default now(),
  ended_at timestamptz,
  source text not null default 'simulated' check (source in ('manual','simulated'))
);

create table emergency_steps (
  id uuid primary key default gen_random_uuid(),   -- client-generated => idempotent retries
  event_id uuid not null references emergency_events(id) on delete cascade,
  ts timestamptz not null default now(),
  step_id text not null,               -- node id in emergency-tree.json
  answer text,                         -- yes | no | free text
  vital_indicator text,                -- optional vital taken during the emergency
  vital_value numeric
);

-- Simulated; modeled after CSA dosimetry fields (type, dose, rate, time, place, instrument)
create table radiation_events (
  id bigserial primary key,
  ts timestamptz not null,
  dose_msv numeric,
  dose_rate_usv_h numeric,
  radiation_type text,                 -- gamma | neutron | mixed
  location text,                       -- cabin | eva | shelter
  instrument text,                     -- e.g. 'simulated-dosimeter-01' (never a real CANS claim)
  event_type text,                     -- background | solar_particle_event
  source text not null default 'simulated' check (source in ('simulated','imported','sensor'))
);

create table doc_chunks (
  id bigserial primary key,
  source_id text not null references sources(id),
  section text,
  hazard text,
  risk text,
  doc_type text,
  published_at date,
  content text not null,
  embedding vector(1024),              -- mistral-embed = 1024 dims
  fts tsvector generated always as (to_tsvector('english', content)) stored
);

create index on measurements (astronaut_id, indicator, ts);
create index on checkins (astronaut_id, day);
create index on emergency_steps (event_id, ts);
create index on doc_chunks using gin (fts);
create index on doc_chunks using hnsw (embedding vector_cosine_ops);

-- Vector search used by the assistant (RAG)
create or replace function match_doc_chunks(query_embedding vector(1024), match_count int default 5)
returns table (id bigint, source_id text, section text, content text, similarity float)
language sql stable as $$
  select id, source_id, section, content, 1 - (embedding <=> query_embedding) as similarity
  from doc_chunks
  order by embedding <=> query_embedding
  limit match_count;
$$;

